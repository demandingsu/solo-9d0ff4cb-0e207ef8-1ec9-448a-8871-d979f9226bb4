from training_portal.service import Portal

CSV_SPRING = """batch,respondent_id,text
B1,R1,春天第一段访谈正文
B1,R2,春天第二段访谈正文
B1,R3,春天第三段访谈正文
"""


@pytest.fixture()
def portal(tmp_path):
    instance = Portal(tmp_path / "data")
    instance.start_workers()
    yield instance
    instance.shutdown()


@pytest.fixture()
def client(tmp_path, monkeypatch):
    instance = Portal(tmp_path / "data")
    monkeypatch.setattr(app_main, "portal", instance)
    with TestClient(app_main.app) as test_client:
        yield test_client, instance
    instance.shutdown()


def make_export(instance: Portal, csv_text: str = CSV_SPRING) -> dict:
    instance.ingest_upload("u.csv", csv_text.encode("utf-8"))
    job_id = instance.create_job("B1")
    deadline = time.monotonic() + 5
    job = None
    while time.monotonic() < deadline:
        job = next(j for j in instance.jobs() if j["id"] == job_id)
        if job["status"] in ("completed", "blocked", "failed"):
            break
        time.sleep(0.05)
    assert job["status"] == "completed"
    return next(e for e in instance.exports() if e["job_id"] == job_id)


def read_export(instance: Portal, export: dict) -> bytes:
    result = instance.open_download(export["id"])
    assert result.error is None and result.file is not None
    try:
        return result.file.read()
    finally:
        result.file.close()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def export_path(instance: Portal, export: dict) -> Path:
    return instance.export_dir / export["stored_name"]


def wait_for_status(
    instance: Portal, export_id: int, status: str, timeout: float = 5.0
) -> dict:
    return wait_for_any_status(instance, export_id, {status}, timeout)


def wait_for_any_status(
    instance: Portal, export_id: int, statuses: set[str], timeout: float = 5.0
) -> dict:
    """Wait until the export is in one of ``statuses``.

    The cleanup worker may delete a locked file before the assertion runs, so
    tests that only care about "no longer downloadable" accept ``deleted`` too.
    """
    deadline = time.monotonic() + timeout
    row = None
    while time.monotonic() < deadline:
        row = next(e for e in instance.exports() if e["id"] == export_id)
        if row["status"] in statuses:
            return row
        time.sleep(0.05)
    raise AssertionError(f"export {export_id} stayed {row and row['status']!r}")


LOCKED = {"pending_delete", "deleted"}


# ---------------------------------------------------------------------------
# publication records a checksum over the generated bytes
# ---------------------------------------------------------------------------
def test_publish_records_checksum_of_exact_downloaded_bytes(portal):
    export = make_export(portal)
    content = read_export(portal, export)
    assert export["content_sha256"] == sha256(content)
    assert export["size_bytes"] == len(content)

    row = next(e for e in portal.exports() if e["id"] == export["id"])
    assert row["integrity"] == "verified"
    assert row["integrity_checked_at"] is not None


def test_publish_rejects_file_changed_before_record_is_written(portal, monkeypatch):
    """A same-length overwrite between writing and record insertion must not publish."""
    real_hash = service.hash_file

    def tampered_hash(path: Path):
        # Simulate the shared volume rewriting the file in place with
        # same-length bytes just before publication verifies it.
        data = bytearray(path.read_bytes())
        for i in range(len(data)):
            data[i] = ord("X")
        path.write_bytes(bytes(data))
        return real_hash(path)

    monkeypatch.setattr(service, "hash_file", tampered_hash)

    portal.ingest_upload("u.csv", CSV_SPRING.encode("utf-8"))
    job_id = portal.create_job("B1")
    deadline = time.monotonic() + 5
    job = None
    while time.monotonic() < deadline:
        job = next(j for j in portal.jobs() if j["id"] == job_id)
        if job["status"] in ("completed", "blocked", "failed"):
            break
        time.sleep(0.05)

    assert job["status"] == "failed"
    assert "校验" in job["message"]
    assert portal.exports() == []
    assert list(portal.export_dir.glob("*.csv")) == []


# ---------------------------------------------------------------------------
# same-length overwrite after publication
# ---------------------------------------------------------------------------
def test_same_length_overwrite_is_refused_and_locks_export(portal):
    export = make_export(portal)
    original = read_export(portal, export)
    path = export_path(portal, export)

    tampered = bytes(b ^ 0xFF for b in original)
    assert len(tampered) == len(original)
    path.write_bytes(tampered)

    result = portal.open_download(export["id"])
    assert result.file is None
    assert result.integrity == "failed"
    assert "校验失败" in result.error

    locked = wait_for_any_status(portal, export["id"], LOCKED)
    assert "校验失败" in (locked["purge_reason"] or "")
    assert "校验失败" in (locked["integrity_error"] or "")

    # A second attempt never serves it again.
    again = portal.open_download(export["id"])
    assert again.file is None and again.error


def test_truncated_file_is_refused_without_partial_csv(portal):
    export = make_export(portal)
    original = read_export(portal, export)
    export_path(portal, export).write_bytes(original[: len(original) // 2])

    result = portal.open_download(export["id"])
    assert result.file is None
    assert result.integrity == "failed"
    assert "长度不符" in result.error
    wait_for_any_status(portal, export["id"], LOCKED)


def test_unreadable_file_is_refused_and_locked(portal):
    export = make_export(portal)
    path = export_path(portal, export)
    path.unlink()
    path.mkdir()  # opening a directory for read fails

    result = portal.open_download(export["id"])
    assert result.file is None
    assert result.integrity == "failed"
    assert "读取" in result.error
    wait_for_any_status(portal, export["id"], LOCKED)

    # Even after the directory is removed, the row stays locked.
    path.rmdir()
    result = portal.open_download(export["id"])
    assert result.file is None and result.error


def test_missing_file_is_refused_and_locked(portal):
    export = make_export(portal)
    export_path(portal, export).unlink()

    result = portal.open_download(export["id"])
    assert result.file is None
    assert result.integrity == "failed"
    wait_for_any_status(portal, export["id"], LOCKED)


# ---------------------------------------------------------------------------
# overwrite while verification is in progress
# ---------------------------------------------------------------------------
def test_second_overwrite_during_verification_never_delivers_new_bytes(
    portal, monkeypatch
):
    """The delivered bytes must come from the verified snapshot, not the path.

    The export is replaced (again) *after* the snapshot copy finished but
    before the caller receives it. Streaming the path would hand out the
    unverified bytes; the snapshot must not.
    """
    export = make_export(portal)
    original = read_export(portal, export)
    path = export_path(portal, export)
    real_copy = service._copy_and_hash

    def copy_then_tamper(source, dest):
        size, digest = real_copy(source, dest)
        # A second same-length overwrite lands while the request is still
        # inside the verification/authorization transaction.
        path.write_bytes(bytes(b ^ 0xFF for b in original))
        return size, digest

    monkeypatch.setattr(service, "_copy_and_hash", copy_then_tamper)

    result = portal.open_download(export["id"])
    assert result.error is None and result.file is not None
    delivered = result.file.read()
    result.file.close()
    assert result.integrity == "verified"
    assert delivered == original
    assert sha256(delivered) == export["content_sha256"]

    # The tamper is still there, so the next request (with the real copier
    # restored) catches it and locks the export.
    monkeypatch.setattr(service, "_copy_and_hash", real_copy)
    result = portal.open_download(export["id"])
    assert result.file is None
    assert result.integrity == "failed"
    wait_for_any_status(portal, export["id"], LOCKED)


def test_concurrent_overwrites_never_deliver_unverified_bytes(portal):
    """Property: every successful response hashes to the recorded digest."""
    export = make_export(portal)
    original_content = read_export(portal, export)
    expected = export["content_sha256"]
    path = export_path(portal, export)
    stop = threading.Event()

    def vandal():
        while not stop.is_set():
            path.write_bytes(bytes(b ^ 0xFF for b in original_content))
            time.sleep(0.001)

    thread = threading.Thread(target=vandal, daemon=True)
    thread.start()
    try:
        for _ in range(25):
            result = portal.open_download(export["id"])
            if result.file is not None:
                delivered = result.file.read()
                result.file.close()
                assert sha256(delivered) == expected
            else:
                assert result.integrity == "failed"
                break
    finally:
        stop.set()
        thread.join(timeout=2)

    row = next(e for e in portal.exports() if e["id"] == export["id"])
    assert row["status"] in ("ready", "pending_delete")
    if row["status"] == "pending_delete":
        result = portal.open_download(export["id"])
        assert result.file is None


