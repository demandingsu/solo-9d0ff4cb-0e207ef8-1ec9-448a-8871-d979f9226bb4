LEGACY_BODY = "batch,respondent_id,text\r\nB1,R1,旧导出内容\r\n"


def insert_legacy_export(instance: Portal) -> int:
    content = LEGACY_BODY.encode("utf-8")
    (instance.export_dir / "export-legacy.csv").write_bytes(content)
    with instance.db.transaction() as conn:
        cursor = conn.execute(
            "INSERT INTO exports(job_id, batch, stored_name, download_name, row_count, "
            "size_bytes, content_sha256, status, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, NULL, 'ready', ?)",
            (
                9001,
                "B1",
                "export-legacy.csv",
                "training-legacy.csv",
                1,
                len(content),
                "2026-01-01T00:00:00+00:00",
            ),
        )
        export_id = int(cursor.lastrowid)
        conn.execute(
            "INSERT INTO export_respondents(export_id, respondent_id) VALUES (?, 'R1')",
            (export_id,),
        )
    return export_id


def test_legacy_export_without_checksum_is_labelled_unverified_and_downloadable(client):
    test_client, instance = client
    export_id = insert_legacy_export(instance)

    response = test_client.get(f"/download/{export_id}")
    assert response.status_code == 200
    assert response.headers["X-Content-Integrity"] == "unverified"
    assert response.content == LEGACY_BODY.encode("utf-8")

    payload = test_client.get("/api/status").json()
    row = next(e for e in payload["exports"] if e["id"] == export_id)
    assert row["integrity"] == "unverified"
    assert row["content_sha256"] is None


def test_legacy_export_unverified_is_visible_on_page(client):
    test_client, instance = client
    insert_legacy_export(instance)
    html = test_client.get("/").text
    assert "未核验" in html


def test_legacy_export_still_obeys_revocation(portal):
    export_id = insert_legacy_export(portal)
    result = portal.open_download(export_id)
    assert result.error is None and result.file is not None
    result.file.close()

    portal.revoke("R1")
    result = portal.open_download(export_id)
    assert result.file is None
    assert "撤回" in result.error


def test_legacy_database_schema_is_migrated_in_place(tmp_path):
    """A database created before verification keeps its rows and gains columns."""
    data_dir = tmp_path / "data"
    data_dir.mkdir()
    db_path = data_dir / "portal.sqlite3"
    import sqlite3

    conn = sqlite3.connect(db_path)
    conn.executescript(
        """
        CREATE TABLE exports (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            job_id INTEGER NOT NULL UNIQUE,
            batch TEXT NOT NULL,
            stored_name TEXT NOT NULL UNIQUE,
            download_name TEXT NOT NULL,
            row_count INTEGER NOT NULL,
            size_bytes INTEGER NOT NULL,
            status TEXT NOT NULL,
            created_at TEXT NOT NULL,
            deleted_at TEXT,
            delete_attempts INTEGER NOT NULL DEFAULT 0,
            last_delete_error TEXT,
            purge_reason TEXT
        );
        INSERT INTO exports(job_id, batch, stored_name, download_name, row_count,
                            size_bytes, status, created_at)
        VALUES (1, 'B1', 'export-old.csv', 'old.csv', 1, 5, 'ready',
                '2026-01-01T00:00:00+00:00');
        """
    )
    conn.commit()
    conn.close()

    instance = Portal(data_dir)
    try:
        columns = {
            row["name"]
            for row in instance.db.connect().execute("PRAGMA table_info(exports)")
        }
        assert {"content_sha256", "integrity_checked_at", "integrity_error"} <= columns
        row = next(e for e in instance.exports() if e["stored_name"] == "export-old.csv")
        assert row["content_sha256"] is None
        assert row["integrity"] == "unverified"
    finally:
        instance.shutdown()


