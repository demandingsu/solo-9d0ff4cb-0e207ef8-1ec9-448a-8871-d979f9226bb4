# persistence: locked across restart
# ---------------------------------------------------------------------------
def test_integrity_failure_stays_locked_after_restart(tmp_path):
    data_dir = tmp_path / "data"
    first = Portal(data_dir)
    first.start_workers()
    try:
        export = make_export(first)
        path = first.export_dir / export["stored_name"]
        original = path.read_bytes()
        path.write_bytes(bytes(b ^ 0xFF for b in original))

        result = first.open_download(export["id"])
        assert result.file is None and result.error
        wait_for_any_status(first, export["id"], LOCKED)
    finally:
        first.shutdown()

    second = Portal(data_dir)
    try:
        row = next(e for e in second.exports() if e["id"] == export["id"])
        assert row["status"] != "ready"
        assert row["integrity"] == "failed"
        result = second.open_download(export["id"])
        assert result.file is None and result.error
    finally:
        second.shutdown()


def test_startup_detects_same_length_overwrite_before_any_download(tmp_path):
    """A restart re-verifies ready exports even if nobody requests one first."""
    data_dir = tmp_path / "data"
    first = Portal(data_dir)
    first.start_workers()
    try:
        export = make_export(first)
        stored = export["stored_name"]
    finally:
        first.shutdown()

    path = data_dir / "exports" / stored
    original = path.read_bytes()
    path.write_bytes(bytes(b ^ 0xFF for b in original))

    second = Portal(data_dir)
    try:
        row = next(e for e in second.exports() if e["id"] == export["id"])
        assert row["status"] == "pending_delete"
        assert row["integrity"] == "failed"
        assert "启动校验" in (row["integrity_error"] or "")
        result = second.open_download(export["id"])
        assert result.file is None
    finally:
        second.shutdown()


